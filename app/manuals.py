"""Реестр руководств базы знаний (раздел 3 ТЗ v6) и привязка к моделям двигателей."""
from dataclasses import dataclass


@dataclass(frozen=True)
class Manual:
    id: str          # внутренний идентификатор, он же имя PDF без расширения
    designation: str  # обозначение документа, как в разделе 3 ТЗ (идёт в references.manual)
    title: str       # человеческое название для механика
    kind: str        # РЭ (эксплуатация) / РК (ремонт) / РЭ+ТО+РК
    year: int
    pages: int
    engines: tuple[str, ...]

    @property
    def filename(self) -> str:
        return f"{self.id}.pdf"


MANUALS: tuple[Manual, ...] = (
    Manual("yamz-236_re_2010", "236-3902150-Б РЭ", "ЯМЗ-236М2. Руководство по эксплуатации", "РЭ", 2010, 172, ("ЯМЗ-236М2",)),
    Manual("yamz-236_rk_2014", "236.01.01 РК", "ЯМЗ-236М2. Руководство по ремонту", "РК", 2014, 287, ("ЯМЗ-236М2",)),
    Manual("yamz-536_re_2016", "536.3902150 РЭ", "ЯМЗ-536. Руководство по эксплуатации", "РЭ", 2016, 285, ("ЯМЗ-536",)),
    Manual("yamz-536_rk_2013", "536.01.02 РК", "ЯМЗ-536. Руководство по ремонту", "РК", 2013, 603, ("ЯМЗ-536",)),
    Manual("zmz-5234_rk_2025", "Двигатели ЗМЗ-5234.10 со сцеплением. Руководство по ремонту",
           "ЗМЗ-5234.10. Руководство по ремонту", "РК", 2025, 158, ("ЗМЗ-5234.10",)),
    Manual("zmz-40904-40905_rk_2025",
           "Двигатели ЗМЗ-40904.10 и ЗМЗ-40905.10. Руководство по эксплуатации, техническому обслуживанию и ремонту",
           "ЗМЗ-40904.10 / 40905.10. Эксплуатация, ТО и ремонт", "РЭ+ТО+РК", 2025, 238,
           ("ЗМЗ-40904.10", "ЗМЗ-40905.10")),
)

BY_ID = {m.id: m for m in MANUALS}


def manuals_for_engine(engine_model: str) -> list[Manual]:
    """Только руководства на двигатель этой машины: норматив от другого двигателя — ошибка (F4 ТЗ)."""
    return [m for m in MANUALS if engine_model in m.engines]


def manual_ids_for_engine(engine_model: str) -> list[str]:
    return [m.id for m in manuals_for_engine(engine_model)]
