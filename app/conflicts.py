"""Противоречия между руководствами, подтвержденные заказчиком.

Агент сам обязан замечать расхождения (правило в промпте). Этот реестр – для случаев, которые заказчик уже разобрал:
если поиск вернул одну из страниц противоречия, агент получает обе формулировки со ссылками и принятое правило.
Текст руководств здесь не хранится – только номера страниц и краткое описание расхождения своими словами.
"""
from __future__ import annotations

import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Conflict:
    topic: str
    pages: tuple[tuple[str, int], ...]   # (manual_id, физическая страница PDF)
    summary: str
    rule: str
    source: str
    topic_re: str = ""                   # запрос механика или агента на эту тему тоже поднимает противоречие
    triggers: tuple[tuple[str, int], ...] = ()   # если задано – поднимают противоречие только эти страницы


CONFLICTS: tuple[Conflict, ...] = (
    Conflict(
        topic="Регулировка тепловых зазоров клапанов ЯМЗ-236",
        pages=(("yamz-236_re_2010", 31), ("yamz-236_rk_2014", 269), ("yamz-236_rk_2014", 276)),
        summary="РЭ допускает регулировку на холодном двигателе или менее чем через 15 минут после остановки, "
                "РК – не ранее чем через 15 минут после остановки.",
        rule="Консервативное правило заказчика для демонстрации: регулировать зазоры на холодном двигателе. "
             "Формулировка РК «не ранее чем через 15 минут» сама по себе не подтверждает, что двигатель остыл. "
             "Покажи обе формулировки со ссылками, назови противоречие и посоветуй уточнить у специалиста "
             "или производителя для этой модификации.",
        source="разъяснение организаторов в чате задачи, 26.11.2026",
        topic_re=r"(тепл\w*\s+)?зазор\w*.{0,40}клапан|клапан\w*.{0,40}зазор|регулир\w*\s+клапан",
    ),
    Conflict(
        topic="Затяжка болтов крышек коренных подшипников ЯМЗ-236",
        pages=(("yamz-236_rk_2014", 41), ("yamz-236_rk_2014", 248)),
        summary="Стр. 41: момент 421–461 Н·м (43–47 кгс·м), в два приема. Стр. 248, раздел «Сборка двигателя»: "
                "421–461 Н·м (42–46 кгс·м), не менее чем в три приема, в заданной очередности опор.",
        rule="Правило выводится из самого руководства: в ньютон-метрах момент на обеих страницах один – 421–461 Н·м, "
             "расходится только пересчет в кгс·м. Стр. 41 сама отсылает к моменту «в разделе Сборка двигателя», "
             "поэтому основная процедура – стр. 248: не менее чем в три приема, в указанной там очередности опор. "
             "Покажи обе страницы со ссылками и объясни, почему берешь стр. 248.",
        source="разъяснение организаторов в чате задачи, 27.11.2026",
        topic_re=r"коренн\w*.{0,60}(болт|крыш|затяж|момент)|(болт|крыш|затяж|момент)\w*.{0,60}коренн",
    ),
    Conflict(
        topic="Давление масла ЯМЗ-236",
        pages=(("yamz-236_rk_2014", 12), ("yamz-236_re_2010", 19), ("yamz-236_rk_2014", 267)),
        summary="Таблица характеристик РК (стр. 12): 400–730 кПа без условий. РЭ стр. 19 и РК стр. 267: 400–700 кПа "
                "на прогретом двигателе (масло 80–100 °С) при номинальной частоте 2100 об/мин и не менее 100 кПа "
                "на минимальной частоте холостого хода.",
        rule="Безопасное правило: норма 400–700 кПа при 2100 об/мин на прогретом двигателе и не менее 100 кПа "
             "на минимальном холостом ходу – так написано в двух местах и с условиями замера. Значение 730 кПа из "
             "таблицы характеристик приведи со ссылкой как расхождение, но нормой не называй.",
        source="разъяснение организаторов в чате задачи, 27.11.2026",
        topic_re=r"730",
        triggers=(("yamz-236_rk_2014", 12),),   # обычный вопрос о давлении масла (С1) не загромождаем
    ),
)


def conflicts_for(pages: set[tuple[str, int]], text: str = "", manuals: set[str] | None = None) -> list[dict]:
    """Противоречия, затронутые найденными страницами или темой запроса, с полным списком ссылок обеих сторон.

    По теме срабатывает только для двигателя, к руководствам которого относится противоречие (manuals)."""
    out = []
    for c in CONFLICTS:
        own = {m for m, _ in c.pages}
        by_topic = bool(c.topic_re and text and manuals is not None and own <= manuals
                        and re.search(c.topic_re, text, re.I))
        if pages & set(c.triggers or c.pages) or by_topic:
            out.append({"topic": c.topic, "refs": [f"{{{m}#{p}}}" for m, p in c.pages],
                        "summary": c.summary, "rule": c.rule, "source": c.source})
    return out
